#!/usr/bin/env python3
"""Generate avmcv710-bootstrap.h from the userspace fast-start bootstrap capture.

Reads the string from cv710userspace's commanddata_cv710_fast.cpp and emits a
compact pre-parsed command table + payload blob suitable for a kernel module.

Token grammar (whitespace separated, identical to UsbStream.cpp):
  '>HEXHEX...'  -> bulk OUT EP1 write of those bytes
  '<N'          -> bulk IN  EP1 read of N bytes (payload ignored, checked for
                   completion; response not used by the fast bootstrap)

Generated file is NOT hand-edited. Regenerate with:
  python3 tools/gen_bootstrap.py [-o avmcv710-bootstrap.h]
"""
import argparse
import re
import sys
from pathlib import Path

USERSRC = (Path(__file__).resolve().parent.parent.parent /
           "cv710userspace/src/liblgx/liblgx-common/src/bootstrap/commanddata_cv710_fast.cpp")


def extract_string(path):
    txt = path.read_text()
    m = re.search(r'std::string\s+\w+\s*\{\s*"(.*)"\s*\}', txt, re.S)
    if not m:
        sys.exit(f"could not locate string literal in {path}")
    return m.group(1)


def parse_commands(s):
    cmds = []  # (op: 0=write 1=read, len, payload bytes)
    blob = bytearray()
    for tok in s.split():
        if not tok:
            continue
        if tok[0] == '>':
            body = tok[1:]
            if len(body) % 2:
                sys.exit(f"odd-length write token: {tok[:40]}...")
            data = bytes.fromhex(body)
            cmds.append((0, len(data), len(blob)))
            blob.extend(data)
        elif tok[0] == '<':
            n = int(tok[1:])
            if n <= 0 or n > 65535:
                sys.exit(f"bad read length token: {tok}")
            cmds.append((1, n, 0))
        else:
            sys.exit(f"unknown token: {tok[:40]}...")
    return cmds, blob


def emit(cmds, blob):
    out = []
    out.append("/* Generated by tools/gen_bootstrap.py - DO NOT EDIT BY HAND. */")
    out.append("/*")
    out.append(" * Fast-start bootstrap for the AVerMedia ExtremeCap U3 (CV710):")
    out.append(" * Cypress FX3 + ADV7604 + ECP3 FPGA. Same write sequence and final")
    out.append(" * register state as the full capture (see cv710userspace PROTOCOL.md),")
    out.append(" * minus I2C status-read round-trips and collapsed poll loops.")
    out.append(" *")
    out.append(" * op=0: bulk OUT EP1 write of 'len' bytes at blob offset 'off'")
    out.append(" * op=1: bulk IN  EP1 read of 'len' bytes (response ignored)")
    out.append(" */")
    out.append("")
    out.append(f"#define AVM_BOOT_CMD_COUNT {len(cmds)}u")
    out.append(f"#define AVM_BOOT_BLOB_BYTES {len(blob)}u")
    out.append("#define AVM_BOOT_OP_WRITE 0u")
    out.append("#define AVM_BOOT_OP_READ  1u")
    out.append("")
    out.append("struct avm_boot_cmd {")
    out.append("\tu8 op;")
    out.append("\tu16 len;")
    out.append("\tu32 off;")
    out.append("};")
    out.append("")
    out.append("static const struct avm_boot_cmd avm_boot_cmds[] = {")
    for op, ln, off in cmds:
        out.append(f"\t{{ {op}, {ln}u, {off}u }},")
    out.append("};")
    out.append("")
    out.append("static const u8 avm_boot_blob[] = {")
    for i in range(0, len(blob), 16):
        row = blob[i:i + 16]
        out.append("\t" + ",".join(f"0x{b:02x}" for b in row) + ",")
    out.append("};")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default="avmcv710-bootstrap.h")
    ap.add_argument("--source", default=str(USERSRC))
    args = ap.parse_args()

    s = extract_string(Path(args.source))
    cmds, blob = parse_commands(s)
    out = emit(cmds, blob)
    Path(args.out).write_text(out)

    n_write = sum(1 for c in cmds if c[0] == 0)
    n_read = sum(1 for c in cmds if c[0] == 1)
    print(f"wrote {args.out}: {len(cmds)} commands ({n_write} writes, {n_read} reads), "
          f"{len(blob)} payload bytes")


if __name__ == "__main__":
    main()